"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { app, BrowserWindow } = require("electron");
const queue = require("../src/youtube-queue");
let window, temporary;
const wait = async check => {
  const until = Date.now() + 5000;
  do { if (await check()) return; await new Promise(resolve => setTimeout(resolve, 30)); } while(Date.now() < until);
  throw Error("Media readiness timed out");
};
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  temporary = fs.mkdtempSync(path.join(os.tmpdir(), "elfix-youtubequeue-"));
  const wav = Buffer.alloc(44 + 16000 * 2);
  wav.write("RIFF", 0); wav.writeUInt32LE(wav.length-8,4); wav.write("WAVEfmt ",8);
  wav.writeUInt32LE(16,16); wav.writeUInt16LE(1,20); wav.writeUInt16LE(1,22);
  wav.writeUInt32LE(8000,24); wav.writeUInt32LE(16000,28); wav.writeUInt16LE(2,32); wav.writeUInt16LE(16,34);
  wav.write("data",36); wav.writeUInt32LE(wav.length-44,40);
  fs.writeFileSync(path.join(temporary,"media.wav"),wav);
  fs.writeFileSync(path.join(temporary,"player.html"), '<div id="movie_player"><video src="media.wav" preload="auto" muted></video></div>');
  window = new BrowserWindow({show:false, webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}});
  await window.loadFile(path.join(temporary,"player.html"),{query:{v:"testVideo01"}});
  const run = code => window.webContents.executeJavaScript(code,true);
  assert.equal(await run(queue.vorbereitenScript("otherVideo1","wrong")),"wrong-video");
  assert.equal(await run("!!window.__elfixQueueHold"),false,"Wrong video cannot install a hold");
  await wait(async () => await run(queue.vorbereitenScript("testVideo01","start-a")) === "ready");
  assert.equal(await run("document.querySelector('video').paused"),true);
  await run("document.querySelector('video').play().catch(()=>{}); void 0");
  await wait(() => run("document.querySelector('video').paused"));
  assert.equal(await run(queue.freigebenScript("stale")),false,"Stale release cannot remove current hold");
  await run("document.querySelector('video').currentTime=1; void 0");
  await wait(async () => await run(queue.vorbereitenScript("testVideo01","start-a")) === "ready");
  assert.equal(await run("document.querySelector('video').currentTime"),0);
  await run("document.querySelector('#movie_player').classList.add('ad-showing')");
  assert.equal(await run(queue.vorbereitenScript("testVideo01","start-a")),"loading","Ads cannot acknowledge content readiness");
  await run("document.querySelector('#movie_player').classList.remove('ad-showing'); document.querySelector('video').outerHTML='<video src=media.wav preload=auto muted></video>'");
  await wait(async () => await run(queue.vorbereitenScript("testVideo01","start-b")) === "ready");
  assert.equal(await run(queue.freigebenScript("start-a")),false,"Prior generation cannot release replacement");
  await run("document.querySelector('video').play().catch(()=>{}); void 0");
  await wait(() => run("document.querySelector('video').paused"));
  assert.equal(await run(queue.freigebenScript("start-b")),true);
  await run("document.querySelector('video').play(); void 0");
  await wait(() => run("!document.querySelector('video').paused && document.querySelector('video').currentTime > .05"));
  console.log("OK YouTube queue: real media readiness, pause/zero, ad exclusion, SPA replacement, generation-safe release and playback");
  window.destroy(); app.exit(0);
}).catch(error => { console.error(error); if(window && !window.isDestroyed()) window.destroy(); app.exit(1); });
